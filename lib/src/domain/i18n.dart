/// The app's languages. Croatian is the source: every text in the code is the
/// Croatian one, with `{0}` and `{1}` for what goes into it, and [tr] finds the
/// other languages here. test/i18n_test.dart checks that none is missing.
library;

enum Language {
  hr('Hrvatski'),
  en('English'),
  tr('Türkçe');

  const Language(this.label);

  /// Its own name, the same in every language.
  final String label;
}

/// The language of everything being shown.
Language language = Language.hr;

/// [text] in the current language, with [values] in place of `{0}`, `{1}`...
String tr(String text, [List<Object?> values = const []]) {
  final row = _texts[text];
  var result = language == Language.hr || row == null ? text : row[language.index - 1];
  for (var i = 0; i < values.length; i++) {
    result = result.replaceAll('{$i}', '${values[i]}');
  }
  return result;
}

/// True when [text] has its English and Turkish forms.
bool isTranslated(String text) => _texts.containsKey(text);

/// English and Turkish forms of every text, for a test to compare.
List<String>? translationsOf(String text) => _texts[text];

